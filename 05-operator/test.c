#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

int main()
{
    // 设置 Windows 控制台输出编码为 UTF-8

    /*
    ==========================
    加减乘除取余
    ==========================
    */

    // + - * / % 都是双目运算符，需要两个操作数
    // %：求模，也就是取余，只能用于整数

    int x = 5 - 22;
    printf("x = %d\n", x);

    // 两个整数相除，结果仍然是整数
    // 6 / 4 = 1
    float y = 6 / 4;
    int z = 6 / 4;

    printf("y = %f, z = %d\n", y, z);

    // 6.0 是浮点数，因此进行浮点除法
    // 结果为 1.5
    float a = 6.0 / 4;
    printf("a = %f\n", a);


    /*
    ==========================
    赋值、自增、自减
    ==========================
    */

    // = 是赋值运算符
    // +=、-= 等复合赋值运算符与 Java 类似

    int b = 10;

    b = b + 3;
    b -= 2;

    printf("b = %d\n", b);


    // ++、-- 是单目运算符，与 Java 类似

    // ++c：先自增，再使用 c 的值
    int c = 10;
    int d = ++c;

    printf("c = %d\n", c);
    printf("d = %d\n", d);


    // f++：先使用 f 原来的值，再自增
    int f = 10;
    int e = f++;

    printf("f = %d\n", f);
    printf("e = %d\n", e);


    /*
    ==========================
    移位运算符
    ==========================
    */

    // << 左移
    // 对于常见的正整数，左移 n 位通常相当于乘以 2^n
    // 移位运算本身不会直接改变原变量

    int num = 10;
    int n = num << 1;

    printf("num = %d\n", num);
    printf("n = %d\n", n);


    // >> 右移
    // 对于非负整数，右移 n 位通常相当于除以 2^n
    // 对负数右移，具体结果与实现有关
    // 常见实现会补符号位

    int num2 = -2;
    int n2 = num2 >> 1;

    printf("num2 = %d\n", num2);
    printf("n2 = %d\n", n2);


    /*
    ==========================
    位操作符
    ==========================
    */

    // & 按位与
    /*
    例如：

      0101 1011
      0011 1101
      ------------
      0001 1001

    对应位上只要有 0，该位结果就是 0
    */

    // | 按位或
    /*
    例如：

      0101 1011
      0011 1101
      ------------
      0111 1111

    对应位上只要有 1，该位结果就是 1
    */

    // ^ 按位异或
    /*
    例如：

      0101 1011
      0011 1101
      ------------
      0110 0110

    对应位相同 → 0
    对应位不同 → 1
    */

    // ~ 按位取反
    /*
    单目运算符

    对应位：
    0 → 1
    1 → 0
    */


    /*
    ==========================
    关系运算符
    ==========================

    >   大于
    <   小于
    >=  大于等于
    <=  小于等于
    !=  不等于
    ==  等于
    */


    /*
    ==========================
    逻辑运算符
    ==========================

    &&  逻辑与
    ||  逻辑或
    !   逻辑非

    后续在 if 语句中学习
    */


    /*
    ==========================
    逗号运算符
    ==========================

    用逗号分隔多个表达式。

    表达式从左向右依次执行，
    整个表达式的结果是最后一个表达式的结果。
    */

    int g = 1;
    int h = 2;

    int i = (g > h, g = h + 10, g, h = g + 1);

    printf("i = %d\n", i);


    /*
    ==========================
    课后习题
    ==========================

    输入一个正整数 n，
    求它的二进制中有多少个 1。
    */

    int num0;
    int count = 0;

    // 输出提示信息
    printf("请输入一个正整数：");

    // 从键盘输入一个整数
    scanf("%d", &num0);

    /*
    判断二进制中有多少个 1：

    n & 1
    ↓
    判断当前最低位是不是 1

    如果是 1：
    count++

    然后：
    n >>= 1
    ↓
    相当于 n = n >> 1
    ↓
    把下一位移动到最低位

    重复这个过程，
    直到 n 变成 0。
    */

    while (num0 != 0)
    {
        // 判断当前最低位是不是 1
        if (num0 & 1)
        {
            // 是 1，计数器加 1
            count++;
        }

        // 右移一位，继续检查下一位
        num0 >>= 1;
    }

    // 输出二进制中 1 的数量
    printf("二进制中有 %d 个 1\n", count);


    return 0;
}
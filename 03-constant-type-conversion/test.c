#include <stdio.h>
int main() {

	int a = 10; // 局部变量（通常存放在栈上）
	a = 20;
	a = 30;
	printf("%d\n", a);

	char c = 'a';

	/*
	===================
	强制数据类型转换
	===================
	*/

	float f = 12.5f;

	int b = (int)f;

	printf("%f\n", f);
	printf("%d\n", b);
	// 浮点数转换为整数时，小数部分被截去


	/*
	===================
	整数溢出
	===================

	数值太大/太小
	↓
	超过数据类型能表示的范围
	↓
	得到异常的数值
	*/
	int i = 32768;
	short sc = i;
	printf("%d\n", sc);
	// 在常见的 16 位 short、二进制补码实现下，输出 -32768

	return 0;
}
#define _CRT_SECURE_NO_WARNINGS

#include <stdio.h>

/*
 * 一维数组
 *
 * 1. 数组声明
 * 2. 数组初始化
 * 3. 数组下标
 * 4. 数组遍历
 * 5. 数组输入输出
 * 6. 数组在内存中的存储
 * 7. sizeof 计算数组长度
 * 8. 数组基本操作
 *    - 修改
 *    - 逆置
 *
 * 注意：
 * 数组下标从 0 开始。
 * int arr[5] 的合法下标为 0 ~ 4。
 */


int main()
{
	// =========================================================
	// 1. 数组声明与初始化
	// =========================================================

	// 声明一个长度为 5 的 int 数组
	int arr[5] = { 1, 2, 3, 4, 5 };

	// 下标从 0 开始
	printf("arr[2] = %d\n", arr[2]);    // 3

	// arr[5] 是越界访问！
	// 合法下标只有 0 ~ 4
	//
	// printf("arr[5] = %d\n", arr[5]);


	// =========================================================
	// 2. 部分初始化
	// =========================================================

	// 没有提供初始值的元素会自动初始化为 0
	int arr1[5] = { 1, 2 };

	printf("\narr1 = ");
	for (int i = 0; i < 5; i++)
	{
		printf("%d ", arr1[i]);
	}
	printf("\n");


	// =========================================================
	// 3. 根据初始化数据自动确定数组长度
	// =========================================================

	int arr2[] = { 1, 2 };

	printf("arr2 = ");
	for (int i = 0; i < 2; i++)
	{
		printf("%d ", arr2[i]);
	}
	printf("\n");


	// =========================================================
	// 4. 遍历数组
	// =========================================================

	printf("\narr = ");

	for (int i = 0; i < 5; i++)
	{
		printf("%d ", arr[i]);
	}

	printf("\n");


	// =========================================================
	// 5. 为数组输入元素
	// =========================================================

	int brr[5] = { 0 };

	printf("\n请输入 5 个整数：\n");

	for (int i = 0; i < 5; i++)
	{
		printf("请输入 brr[%d]：", i);
		scanf("%d", &brr[i]);
	}

	printf("输入后的 brr = ");

	for (int i = 0; i < 5; i++)
	{
		printf("%d ", brr[i]);
	}

	printf("\n");


	// =========================================================
	// 6. 一维数组在内存中的存储
	// =========================================================

	printf("\n数组 brr 的内存地址：\n");

	for (int i = 0; i < 5; i++)
	{
		/*
		 * %p 用于输出地址
		 *
		 * 数组中的元素在内存中是连续存储的。
		 * 如果 int 占 4 个字节，
		 * 那么相邻两个元素的地址通常相差 4。
		 */

		printf("&brr[%d] = %p\n", i, &brr[i]);
	}


	// =========================================================
	// 7. 使用 sizeof 计算数组长度
	// =========================================================

	int len = sizeof(arr) / sizeof(arr[0]);

	printf("\narr 的长度 = %d\n", len);


	// =========================================================
	// 8. 数组逆置
	// =========================================================

	int crr[] = { 1, 2, 3, 4, 5 };

	int len1 = sizeof(crr) / sizeof(crr[0]);

	printf("\n原数组：");

	for (int i = 0; i < len1; i++)
	{
		printf("%d ", crr[i]);
	}

	// 首尾两个下标
	int i = 0;
	int j = len1 - 1;

	// 首尾交换，逐渐向中间靠拢
	while (i < j)
	{
		int temp = crr[i];

		crr[i] = crr[j];
		crr[j] = temp;

		i++;
		j--;
	}

	printf("\n逆置后：");

	for (int i = 0; i < len1; i++)
	{
		printf("%d ", crr[i]);
	}

	printf("\n");


	// =========================================================
	// 9. 修改数组中的元素
	// =========================================================

	printf("\narr 原来的值：");

	for (int i = 0; i < len; i++)
	{
		printf("%d ", arr[i]);
	}

	// 将每个元素扩大 2 倍
	for (int i = 0; i < len; i++)
	{
		arr[i] = arr[i] * 2;
	}

	printf("\narr 扩大 2 倍后：");

	for (int i = 0; i < len; i++)
	{
		printf("%d ", arr[i]);
	}

	printf("\n");





	/*
		二维数组
	*/

	//二维数组的创建和初始化 以及下标

	//完全初始化
	int array1[2][3] = { 1,2,3,4,5,6 };	//array[0][1]=2;

	int array2[2][3] = { {1,2,3},{4,5,6} };

	int array3[2][3] = { {1,2,3},{4} };//未初始化的元素为0

	//C语言中，可以省略行，但是不能省略列
	//前者是行，后者是列
	int array4[][3] = { 1,2,3,4,5,6 };

	printf("\n");
	//打印二维数组array1
	for (int i = 0;i < 2; i++)
	{
		for (int j = 0;j < 3;j++)
		{
			printf("array1[%d][%d] = %d \n", i, j, array1[i][j]);
		}
	}
	printf("\n");

	//二维数组的内存也是连续的
	//case 1 :矩阵置换

	int array[3][3] = { {1,2,3},{4,5,6},{7,8,9} };



	//方法一
	/*
	int temp[3][3];
	for (int i = 0;i < 3;i++)
	{
		for (int j = 0;j < 3;j++)
		{
			temp[j][i] = array[i][j];
		}
	}
	
	//输出
	for (int i = 0;i < 3; i++)
	{
		for (int j = 0;j < 3;j++)
		{
			printf("array[%d][%d] = %d ", i, j, temp[i][j]);
		}
		printf("\n");
	}
	
	*/

	//方法二
	for (int i = 0;i < 3;i++)
	{
		for (int j = i + 1;j < 3;j++)
		{
			int temp = array[i][j];
			array[i][j] = array[j][i];
			array[j][i] = temp;

		}
	}
	//输出
	for (int i = 0;i < 3; i++)
	{
		for (int j = 0;j < 3;j++)
		{
			printf("array[%d][%d] = %d ", i, j, array[i][j]);
		}
		printf("\n");
	}


	

	return 0;
}


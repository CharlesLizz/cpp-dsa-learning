//
void print_arr(int* p, int len)
{
	for (int i = 0;i < len;i++)
	{
		printf("%d ", *(p + i));
	}

	printf("\n");

	/*
	两种写法等价，[]的作用拓展
	for (int i = 0;i < len;i++)
	{
		printf("%d ", p[i]);
	}
	*/

}





	//printf("*(arr5 + 1) = %d\n", *(arr5 + 1));

	printf("*(arr5 + 1) = %p\n", *(arr5 + 1));
	//相当于输出 arr5[1],也就是&b1,所以实际上应该使用%p
	printf("**(arr5 + 1) = %d\n", **(arr5 + 1));
	//这里两次解引用，相当于输出b1的值，也就是20

	/*
	=============================数组指针==========================
	*/
	//类比指针数组，数组指针是 指针，也就是指向数组的指针
	//那么怎么表示数组的地址？  &+数组名 代表的就是整个数组的地址

	int arr6[] = { 1,2,3,4 ,5 };
	//int* p7 = &arr6;//此处写法其实有问题，“int *”与“int (*)[5]”的间接级别不同


	int (*p7)[5] = &arr6;
	//数组的长度是5 数组的类型是整型数组
	//（*p7）表示p7是一个指针,[5]代表 该指针 指向的是长度为5的数组
	//这个数组是int类型的数组

	//如果 p7+1，就要加 5×sizeof（int）个字节


	//case
	char* ch[] = { "work","at","alibaba" };
	char** pch = ch;
	pch++;//由于是指针类型，那么+1的话，其实就是+8个字节，也就是一个指针大小
